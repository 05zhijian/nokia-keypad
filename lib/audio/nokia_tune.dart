import '../model/note_token.dart';

/// 诺基亚经典铃声（Tárrega《Gran Vals》选段），预置在编辑器里。
///
/// 记谱是本项目自己的 `{时值}[#]{音}[@八度]`，语法见 [parseNoteToken]。
///
/// **可信度说明**（这段值得写清楚，因为「一按就听出来是诺基亚」全押在它上面）：
/// - 音高走向 `E D F# G# / C# B D E / B A C# E / A` 经两个独立来源核对一致
///   （吉他谱反推 + 流传最广的 RTTTL 转写）。
/// - 但**中段的八度归属**（`D5 E5` 还是 `D6 E6`）两来源同源，无法交叉验证。
///   若听着不像，改这里的 `@5` 为 `@6` 即可——这份常量就是留给你改的。
///
/// 时值：8 = 八分音符，4 = 四分音符，2 = 二分音符。
const nokiaTuneNotation = <String>[
  '83@6', // E6  八分
  '82@6', // D6  八分
  '4#4@5', // F#5 四分
  '4#5@5', // G#5 四分
  '8#1@6', // C#6 八分
  '87@5', // B5  八分
  '42@5', // D5  四分
  '43@5', // E5  四分
  '87@5', // B5  八分
  '86@5', // A5  八分
  '4#1@5', // C#5 四分
  '43@5', // E5  四分
  '26@5', // A5  二分
];

/// 解析好的诺基亚铃声。
List<NoteToken> nokiaTune() =>
    [for (final notation in nokiaTuneNotation) parseNoteToken(notation)];
